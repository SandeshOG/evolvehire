-- Evolve Hire 003 — content catalogues and site settings (parity with the Node app).

CREATE TABLE IF NOT EXISTS settings (
  skey VARCHAR(60) NOT NULL PRIMARY KEY,
  svalue TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS industries (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  slug VARCHAR(190) NOT NULL,
  summary VARCHAR(300) NOT NULL DEFAULT '',
  sort_order INT NOT NULL DEFAULT 0,
  published TINYINT NOT NULL DEFAULT 1,
  UNIQUE KEY industries_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS functions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  slug VARCHAR(190) NOT NULL,
  summary VARCHAR(300) NOT NULL DEFAULT '',
  sort_order INT NOT NULL DEFAULT 0,
  published TINYINT NOT NULL DEFAULT 1,
  UNIQUE KEY functions_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS services (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  slug VARCHAR(190) NOT NULL,
  summary VARCHAR(300) NOT NULL DEFAULT '',
  body TEXT NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  published TINYINT NOT NULL DEFAULT 1,
  UNIQUE KEY services_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS insights (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  slug VARCHAR(190) NOT NULL,
  excerpt VARCHAR(300) NOT NULL DEFAULT '',
  body TEXT NOT NULL,
  published TINYINT NOT NULL DEFAULT 0,
  published_at TIMESTAMP NULL DEFAULT NULL,
  UNIQUE KEY insights_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS case_studies (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  slug VARCHAR(190) NOT NULL,
  excerpt VARCHAR(300) NOT NULL DEFAULT '',
  body TEXT NOT NULL,
  industry VARCHAR(180) NOT NULL DEFAULT '',
  published TINYINT NOT NULL DEFAULT 0,
  published_at TIMESTAMP NULL DEFAULT NULL,
  UNIQUE KEY case_studies_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS companies (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  slug VARCHAR(190) NOT NULL,
  summary VARCHAR(300) NOT NULL DEFAULT '',
  website VARCHAR(300) NOT NULL DEFAULT '',
  published TINYINT NOT NULL DEFAULT 0,
  UNIQUE KEY companies_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
